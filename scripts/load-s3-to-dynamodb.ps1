# Load S3 Data into DynamoDB Tables
# This script reads CSV/JSON data from S3 and loads it into DynamoDB tables

param(
    [string]$AccountId = "060002399377",
    [string]$Region = "us-east-1",
    [switch]$SkipDownload = $false
)

Write-Host "Loading S3 data into DynamoDB tables..." -ForegroundColor Cyan

# Define bucket and table names
$rawDataBucket = "retailmind-raw-data-$AccountId"
$transactionsTable = "retailmind-transactions"

# Create temporary directory for downloads
$tempDir = "temp-data-load"
New-Item -ItemType Directory -Force -Path $tempDir | Out-Null

try {
    # Step 1: Download data from S3 (or use local sample data)
    Write-Host "`n[1/4] Preparing data..." -ForegroundColor Yellow
    
    if (-not $SkipDownload) {
        Write-Host "  Downloading from S3..." -ForegroundColor Gray
        $transactionsFile = "$tempDir/transactions.csv"
        aws s3 cp "s3://$rawDataBucket/transactions/2024/03/transactions.csv" $transactionsFile 2>&1 | Out-Null
        
        if ($LASTEXITCODE -ne 0) {
            Write-Host "  ⚠ S3 download failed, using local sample data instead" -ForegroundColor Yellow
            $SkipDownload = $true
        } else {
            Write-Host "  ✓ Downloaded from S3" -ForegroundColor Green
        }
    }
    
    if ($SkipDownload) {
        Write-Host "  Creating sample data locally..." -ForegroundColor Gray
        # Create sample transaction data
        $transactionData = @"
transaction_id,date,product_id,product_name,category,quantity,unit_price,total_amount,store_id,customer_id
TXN001,2024-03-01T10:30:00Z,P001,Laptop,Electronics,2,899.99,1799.98,S001,C001
TXN002,2024-03-01T11:15:00Z,P002,Mouse,Electronics,5,29.99,149.95,S001,C002
TXN003,2024-03-02T09:45:00Z,P003,Keyboard,Electronics,3,79.99,239.97,S002,C003
TXN004,2024-03-02T14:20:00Z,P004,Monitor,Electronics,1,299.99,299.99,S001,C001
TXN005,2024-03-03T16:00:00Z,P005,Desk Chair,Furniture,2,199.99,399.98,S003,C004
TXN006,2024-03-03T10:30:00Z,P001,Laptop,Electronics,1,899.99,899.99,S002,C005
TXN007,2024-03-04T13:45:00Z,P006,Notebook,Stationery,10,4.99,49.90,S001,C002
TXN008,2024-03-04T15:30:00Z,P007,Pen Set,Stationery,15,9.99,149.85,S003,C006
TXN009,2024-03-05T11:00:00Z,P008,Backpack,Accessories,4,49.99,199.96,S002,C007
TXN010,2024-03-05T14:15:00Z,P009,Water Bottle,Accessories,8,19.99,159.92,S001,C003
"@
        $transactionsFile = "$tempDir/transactions.csv"
        $transactionData | Out-File -FilePath $transactionsFile -Encoding utf8
        Write-Host "  ✓ Sample data created" -ForegroundColor Green
    }

    # Step 2: Load transactions into DynamoDB
    Write-Host "`n[2/4] Loading transactions into DynamoDB..." -ForegroundColor Yellow
    
    # Read CSV file
    $transactions = Import-Csv -Path $transactionsFile
    $successCount = 0
    $errorCount = 0
    
    foreach ($transaction in $transactions) {
        # Create DynamoDB item JSON
        $item = @{
            transactionId = @{ S = $transaction.transaction_id }
            timestamp = @{ S = $transaction.date }
            productId = @{ S = $transaction.product_id }
            productName = @{ S = $transaction.product_name }
            category = @{ S = $transaction.category }
            quantity = @{ N = $transaction.quantity }
            unitPrice = @{ N = $transaction.unit_price }
            totalAmount = @{ N = $transaction.total_amount }
            storeId = @{ S = $transaction.store_id }
            customerId = @{ S = $transaction.customer_id }
        } | ConvertTo-Json -Compress
        
        # Put item into DynamoDB
        aws dynamodb put-item `
            --table-name $transactionsTable `
            --item $item `
            --region $Region `
            2>&1 | Out-Null
        
        if ($LASTEXITCODE -eq 0) {
            $successCount++
            Write-Host "  ✓ Loaded: $($transaction.transaction_id) - $($transaction.product_name)" -ForegroundColor Gray
        } else {
            $errorCount++
            Write-Host "  ✗ Failed: $($transaction.transaction_id)" -ForegroundColor Red
        }
    }
    
    Write-Host "`n✓ Loaded $successCount transactions" -ForegroundColor Green
    if ($errorCount -gt 0) {
        Write-Host "⚠ $errorCount transactions failed" -ForegroundColor Yellow
    }

    # Step 3: Create sample business intelligence data
    Write-Host "`n[3/4] Creating sample business intelligence data..." -ForegroundColor Yellow
    
    # Note: This would normally come from your AI agents
    # For now, we'll create sample data to make the dashboard functional
    Write-Host "  ℹ Business intelligence is generated by AI agents" -ForegroundColor Gray
    Write-Host "  ℹ Run agent workflows to populate this data" -ForegroundColor Gray

    # Step 4: Verify data in DynamoDB
    Write-Host "`n[4/4] Verifying data in DynamoDB..." -ForegroundColor Yellow
    
    $scanResult = aws dynamodb scan `
        --table-name $transactionsTable `
        --select COUNT `
        --region $Region `
        --output json 2>&1 | ConvertFrom-Json
    
    if ($scanResult.Count) {
        $itemCount = $scanResult.Count
        Write-Host "✓ DynamoDB table contains $itemCount items" -ForegroundColor Green
    } else {
        Write-Host "⚠ Could not verify item count" -ForegroundColor Yellow
    }

    # Summary
    Write-Host "`n================================" -ForegroundColor Cyan
    Write-Host "Data Load Complete!" -ForegroundColor Green
    Write-Host "================================" -ForegroundColor Cyan
    Write-Host "`nSummary:" -ForegroundColor White
    Write-Host "  • Transactions loaded: $successCount" -ForegroundColor Green
    Write-Host "  • Table: $transactionsTable" -ForegroundColor Gray
    Write-Host "  • Region: $Region" -ForegroundColor Gray
    
    if ($successCount -gt 0) {
        Write-Host "`n✓ Your API can now serve this data!" -ForegroundColor Yellow
    }
    
} catch {
    Write-Host "`n✗ Error loading data: $_" -ForegroundColor Red
    Write-Host $_.Exception.Message -ForegroundColor Red
    exit 1
} finally {
    # Cleanup
    if (Test-Path $tempDir) {
        Remove-Item -Recurse -Force $tempDir
    }
}

